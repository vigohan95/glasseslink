import io

doc = u'''# 现在就能试的三分钟流程

前提：iPhone 上已装 GlassesLink（Sideloadly 免费签名即可），电脑上不需要跑任何东西。

## 0. 先让眼镜愿意说话（这一步不能省）

1. 把眼镜**双镜腿折起来**
2. **长按右侧拍摄键约 5 秒**，直到镜框内侧指示灯**闪蓝**（不是白、不是橙）
3. 这时**展开镜腿**，把眼镜放在手机旁边 30 cm 内

> 闪蓝 = 它正在广播自己。灯不闪蓝，app 里永远扫不到，这不是 app 的问题。

## 1. 连接

- 打开 app → 第一页「相册」→ 顶部会列出设备
- 看到 `RB Meta 046N`（可能带「Meta 眼镜」标记）→ **点一次**
- 等 5 秒，看页面顶部状态胶囊：`已连接` 或一行失败原因

**只点一次。** 连点会占住 PSM，反而更慢。

## 2. 看"主人身份"这一行

进「设备」→ 看「主人身份」这一栏：

| 显示 | 含义 | 你要做什么 |
|---|---|---|
| 已通过（这台 iPhone 是主人） | 成功 | 回相册拉照片，去设置改东西 |
| 未验证（临时密钥，仅用于注册） | 链路通了，但还没当主人 | 做第 3 步 |
| 眼镜不认识这把钥匙（0x1010） | 眼镜里没我们的钥匙 | 做第 3 步的 A |
| 签名不被接受（0x1044） | 钥匙不对 | 做第 3 步的 A |
| 眼镜属于另一个 Meta 账号（0x1042） | 账号不同 | 做第 3 步的 B |

## 3. 成为主人（两条路，按第 2 步的结果选）

### A. 导入 Visor 那把钥匙（推荐，不碰 Meta）

1. 那台安卓上还装着补丁版 Visor（图标与正版并排，名字一样）
2. 打开它 → 跟着走「登录 → 配对」→ 完成后
3. 安卓的**下载/Download** 里会出现 `visor-owner-4V0ZW04H7J046N.json`
4. 把它传到 iPhone（微信/邮件/AirDrop 都行）
5. iPhone：设备 → 成为这副眼镜的主人 → **① 用上次导出的钥匙文件导入** → 选那个 json
6. 回相册页点一次连接 → 应该变成「已通过」

### B. 让 iPhone 自己注册（需要 Meta 登录一次）

1. iPhone：设备 → 成为这副眼镜的主人 → **② 现在向 Meta 注册**
2. 弹出 Meta 登录页（只这一次，之后再也不联网）
3. 登录后 app 会提示「请连按眼镜拍摄键 3–5 次确认」
4. 完成后再点一次连接

> 用哪个 Meta 账号很重要：必须和当初给眼镜做初始设置的账号**同一个**，否则会看到 0x1042。

## 4. 无论成功还是失败，请把这段话发出来

设备 → 高级 → **复制全部**

粘出来长这样：

```
GlassesLink 0.55 (55) · iOS 27.2 · iPhone
owner pubkey(SHA256) …
owner source …
trust …
link …
--- log ---
…
```

有了它，失败原因不用猜。

## 常见卡点

| 现象 | 原因 | 解法 |
|---|---|---|
| 扫描列表里没有任何 Meta 设备 | 眼镜没进配对模式，或还被安卓连着 | 关掉安卓蓝牙；重新折叠长按 5 秒到闪蓝 |
| 点了连接没反应 | 上一次连接还占着 | 等 5 秒再点；或先点「断开」 |
| 打开就闪退 | 旧版本（0.39 之前） | 装 0.55 |
| 拉到一半断了 | 蓝牙距离/干扰，或眼镜休眠 | 眼镜展开、靠近、别隔着身体 |
| 照片导入很慢 | 蓝牙约 150 KB/s，2.7 MB 约 20–30 秒 | 正常；视频建议先拍短的 |
'''

